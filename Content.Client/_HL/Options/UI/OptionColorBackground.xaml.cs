using System.Collections.Frozen;
using Content.Client.Options.UI;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._HL.Options.UI;

/// <summary>
///  UI control used for Text and Background colour sliders in the options menu. Intended for use with <see cref="OptionsTabControlRow"/>.
/// </summary>
/// <seealso cref="OptionsTabControlRow.AddOptionColorBackground"/>
[GenerateTypedNameReferences]
public sealed partial class OptionColorBackground : Control
{
    public readonly FrozenSet<ColorSelectorSliders> Sliders;


    public OptionColorBackground()
    {
        RobustXamlLoader.Load(this);
        Sliders = new[]
        {
            BackgroundSlider,
            TextSlider,
        }.ToFrozenSet();
    }

    /// <summary>
    /// The text describing what this slider affects.
    /// </summary>
    public string? Title
    {
        get => TitleLabel.Text;
        set => TitleLabel.Text = value;
    }

    /// <summary>
    /// A way to pass a styleclass to the example text. Getter is always null
    /// </summary>
    public string? ExampleStyle
    {
        get => null;
        set
        {
            if (value is not null)
                ExampleLabel.SetOnlyStyleClass(value);
        }
    }

    /// <summary>
    /// The example text showing the current color of the slider.
    /// </summary>
    public string? Example
    {
        get => ExampleLabel.Text;
        set => ExampleLabel.Text = value;
    }
}
