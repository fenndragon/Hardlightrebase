using Content.Client.Guidebook.Controls;
using Content.Client.Guidebook.Richtext;
using Content.Client.Message;
using Content.Client.UserInterface.ControlExtensions;
using Content.Shared._HL.Guidebook;
using JetBrains.Annotations;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;
using System.Diagnostics.CodeAnalysis;

namespace Content.Client._HL.Guidebook;

[UsedImplicitly, GenerateTypedNameReferences]
public sealed partial class GuideSpaceLawModifierEmbed : BoxContainer, IDocumentTag, ISearchableControl, IPrototypeRepresentationControl
{
    [Dependency] private ILogManager _logManager = default!;
    [Dependency] private IPrototypeManager _prototype = default!;

    private readonly ISawmill _sawmill;

    public IPrototype? RepresentedPrototype { get; private set; }

    public GuideSpaceLawModifierEmbed()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _sawmill = _logManager.GetSawmill("guidebook.spacelaw");
        MouseFilter = MouseFilterMode.Stop;
    }

    public GuideSpaceLawModifierEmbed(SpaceLawModifierPrototype modifier) : this()
    {
        GenerateControl(modifier);
    }

    public bool CheckMatchesSearch(string query)
    {
        return this.ChildrenContainText(query);
    }

    public void SetHiddenState(bool state, string query)
    {
        Visible = CheckMatchesSearch(query) ? state : !state;
    }

    public bool TryParseTag(Dictionary<string, string> args, [NotNullWhen(true)] out Control? control)
    {
        control = null;
        if (!args.TryGetValue("Modifier", out var id))
        {
            _sawmill.Error("Space Law Modifier embed tag is missing `Modifier` prototype argument");
            return false;
        }

        if (!_prototype.TryIndex<SpaceLawModifierPrototype>(id, out var modifier))
        {
            _sawmill.Error($"Specified modifier prototype \"{id}\" is not a valid SpaceLawModifier prototype");
            return false;
        }

        GenerateControl(modifier);
        control = this;
        return true;
    }

    private void GenerateControl(SpaceLawModifierPrototype modifier)
    {
        RepresentedPrototype = modifier;
        NameBackground.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#1b67a5")
        };

        var fullName = $"{modifier.Code} - {modifier.Name}";
        ModifierFullName.SetMarkup(Loc.GetString("guidebook-spacelaw-name", ("color", Color.White), ("name", fullName)));
        SetMessage(ModifierDescription, modifier.Description);
        SetMessage(ModifierAdjustment, modifier.Adjustment);
    }

    private static void SetMessage(RichTextLabel label, string value)
    {
        var message = new FormattedMessage();
        message.AddMarkupOrThrow(value);
        label.SetMessage(message);
    }
}
