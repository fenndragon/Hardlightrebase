
using Content.Client.Guidebook.Richtext;
using JetBrains.Annotations;
using Robust.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using System.Diagnostics.CodeAnalysis;
using Robust.Client.UserInterface;
using Robust.Shared.Prototypes;
using Robust.Client.UserInterface.XAML;
using Content.Shared._HL.Guidebook;

namespace Content.Client._HL.Guidebook;

/// <summary>
///     Control for generating a list of space laws
/// </summary>
[UsedImplicitly, GenerateTypedNameReferences]
public sealed partial class GuideSpaceLawGroupEmbed : BoxContainer, IDocumentTag
{
    [Dependency] private IPrototypeManager _prototype = default!;
    [Dependency] private readonly ILogManager _logManager = default!;
    private ISawmill _sawmill;

    public GuideSpaceLawGroupEmbed()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _sawmill = _logManager.GetSawmill("guidebook.spacelaw");
        MouseFilter = MouseFilterMode.Stop;
    }

    public GuideSpaceLawGroupEmbed(string severity) : this()
    {
        var prototypes = _prototype.EnumeratePrototypes<SpaceLawPrototype>()
            .Where(p => p.Severity.Equals(severity)).OrderBy(p => p.Code);
        foreach (var law in prototypes)
        {
            var embed = new GuideSpaceLawEmbed(law);
            GroupContainer.AddChild(embed);
        }
    }

    public bool TryParseTag(Dictionary<string, string> args, [NotNullWhen(true)] out Control? control)
    {
        control = null;
        var prototypes = _prototype.EnumeratePrototypes<SpaceLawPrototype>();
        if (!args.TryGetValue("Severity", out var severity))
        {
            foreach (var law in prototypes.OrderBy(p => p.Code))
            {
                var embed = new GuideSpaceLawEmbed(law);
                GroupContainer.AddChild(embed);
            }
        }
        else
        {
            foreach (var law in prototypes.Where(p => p.Severity.ToString().Equals(severity)).OrderBy(p => p.Code))
            {
                var embed = new GuideSpaceLawEmbed(law);
                GroupContainer.AddChild(embed);
            }
        }
        control = this;
        return true;
    }
}
