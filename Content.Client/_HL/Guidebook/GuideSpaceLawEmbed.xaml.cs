
using Content.Client.Guidebook.Controls;
using Content.Client.Guidebook.Richtext;
using JetBrains.Annotations;
using Robust.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Shared.Prototypes;
using Content.Shared._HL.Guidebook;
using Robust.Client.UserInterface.XAML;
using Content.Client.UserInterface.ControlExtensions;
using System.Diagnostics.CodeAnalysis;
using Robust.Client.UserInterface;
using Robust.Client.Graphics;
using Content.Client.Message;
using Robust.Shared.Utility;

namespace Content.Client._HL.Guidebook;

[UsedImplicitly, GenerateTypedNameReferences]
public sealed partial class GuideSpaceLawEmbed : BoxContainer, IDocumentTag, ISearchableControl, IPrototypeRepresentationControl
{
    [Dependency] private ILogManager _logManager = default!;
    [Dependency] private IPrototypeManager _prototype = default!;

    private readonly ISawmill _sawmill;

    public IPrototype? RepresentedPrototype { get; private set; }

    public GuideSpaceLawEmbed()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _sawmill = _logManager.GetSawmill("guidebook.spacelaw");
        MouseFilter = MouseFilterMode.Stop;
    }

    public GuideSpaceLawEmbed(string law) : this()
    {
        GenerateControl(_prototype.Index<SpaceLawPrototype>(law));
    }

    public GuideSpaceLawEmbed(SpaceLawPrototype law) : this()
    {
        GenerateControl(law);
    }

    public bool CheckMatchesSearch(string query)
    {
        return this.ChildrenContainText(query);
    }

    public void SetHiddenState(bool state, string query)
    {
        Visible = CheckMatchesSearch(query) ? state : !state;
    }

    public bool TryParseTag(Dictionary<string, string> args, [NotNullWhen(true)] out Control? control)
    {
        control = null;
        if (!args.TryGetValue("Law", out var id))
        {
            _sawmill.Error("Space Law Embeded Tag is missing `Law` prototype argument");
            return false;
        }

        if (!_prototype.TryIndex<SpaceLawPrototype>(id, out var law))
        {
            _sawmill.Error($"Specified Law prototype \"{id}\" is not a valid HLSpaceLaw prototype");
            return false;
        }

        GenerateControl(law);
        control = this;
        return true;
    }

    private void GenerateControl(SpaceLawPrototype law)
    {
        RepresentedPrototype = law;
        NameBackground.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.LightGray
        };

        var textColor = Color.Black;
        var fullName = $"{law.Code} - {law.Name}";
        var prototypes = _prototype.EnumeratePrototypes<SpaceLawPrototype>();

        LawFullName.SetMarkup(Loc.GetString("guidebook-spacelaw-name", ("color", textColor), ("name", fullName)));

        if (law.Elements.Any())
        {
            var label = new RichTextLabel()
            {
                Margin = new Thickness(25, 0, 10, 0)
            };
            var msg = new FormattedMessage();
            var count = law.Elements.Count();
            var i = 0;
            foreach (var element in law.Elements)
            {
                msg.AddMarkupOrThrow(element);
                i++;
                if (i < count)
                    msg.PushNewline();
            }
            label.SetMessage(msg);
            ElementsDescriptionContainer.AddChild(label);
        }

        if (law.Punishment.Any())
        {
            var label = new RichTextLabel()
            {
                Margin = new Thickness(25, 0, 10, 0)
            };
            var msg = new FormattedMessage();
            var count = law.Punishment.Count();
            var i = 0;
            foreach (var punishment in law.Punishment)
            {
                msg.AddMarkupOrThrow(punishment);
                i++;
                if (i < count)
                    msg.PushNewline();
            }
            label.SetMessage(msg);
            PunishmentDescriptionContainer.AddChild(label);
        }

        var lesser = prototypes.Where(x => x.Greater.Contains(law) );
        foreach (var less in lesser)
        {
            var label = new GuidebookRichPrototypeLink()
            {
                Margin = new Thickness(25, 0, 0, 0),
                LinkedPrototype = less
            };
            var msg = new FormattedMessage();
            msg.AddMarkupOrThrow($"Lesser: {less.Code} - {less.Name}");
            label.SetMessage(msg);
            RelatedDescriptionContainer.AddChild(label);
        }

        foreach (var greater in law.Greater)
        {
            var proto = _prototype.Index(greater);
            var label = new GuidebookRichPrototypeLink()
            {
                Margin = new Thickness(25, 0, 0, 0),
                LinkedPrototype = proto
            };
            var msg = new FormattedMessage();
            msg.AddMarkupOrThrow($"Greater: {proto.Code} - {proto.Name}");
            label.SetMessage(msg);
            RelatedDescriptionContainer.AddChild(label);
        }


        if (law.Description.Length > 0)
        {
            var label = new RichTextLabel()
            {
                Margin = new Thickness(25, 0, 10, 0)
            };
            var msg = new FormattedMessage();
            msg.AddMarkupOrThrow(law.Description);
            label.SetMessage(msg);
            TextDescriptionContainer.AddChild(label);
        }
    }
}
